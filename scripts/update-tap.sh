#!/usr/bin/env bash
# Render Formula/ttmux.rb for a released version and push it to the tap.
#
# The formula installs the binaries that the release workflow already built,
# so this reads their checksums from the release rather than computing any.
#
# usage: scripts/update-tap.sh v0.1.0
set -euo pipefail

TAG="${1:?usage: update-tap.sh <tag>}"
VERSION="${TAG#v}"
REPO="${REPO:-statico/ttmux}"
TAP="${TAP:-statico/homebrew-tap}"

TARGETS=(
  aarch64-apple-darwin
  x86_64-apple-darwin
  aarch64-unknown-linux-gnu
  x86_64-unknown-linux-gnu
)

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

for t in "${TARGETS[@]}"; do
  gh release download "$TAG" --repo "$REPO" \
    --pattern "ttmux-$t.tar.gz.sha256" --dir "$work" --clobber
done

# The .sha256 files hold "<hash>  <filename>", so the hash is the first field.
# A function rather than an associative array, because macOS ships bash 3.2.
sha() { awk '{print $1}' "$work/ttmux-$1.tar.gz.sha256"; }
url() { echo "https://github.com/$REPO/releases/download/$TAG/ttmux-$1.tar.gz"; }

cat > "$work/ttmux.rb" <<EOF
# Generated by scripts/update-tap.sh in $REPO. Edits here are overwritten
# by the next release.
class Ttmux < Formula
  desc "Modern multiplexer alternative with tiling and free-floating panes"
  homepage "https://github.com/$REPO"
  version "$VERSION"
  license "MIT"

  on_macos do
    on_arm do
      url "$(url aarch64-apple-darwin)"
      sha256 "$(sha aarch64-apple-darwin)"
    end
    on_intel do
      url "$(url x86_64-apple-darwin)"
      sha256 "$(sha x86_64-apple-darwin)"
    end
  end

  on_linux do
    on_arm do
      url "$(url aarch64-unknown-linux-gnu)"
      sha256 "$(sha aarch64-unknown-linux-gnu)"
    end
    on_intel do
      url "$(url x86_64-unknown-linux-gnu)"
      sha256 "$(sha x86_64-unknown-linux-gnu)"
    end
  end

  def install
    bin.install "ttmux"
  end

  test do
    assert_match "ttmux #{version}", shell_output("#{bin}/ttmux -V")
    # --where needs no terminal, so it works in the sandbox.
    assert_match "ttmux.toml", shell_output("#{bin}/ttmux --where")
  end
end
EOF

# Commit through the contents API rather than git: GitHub signs those
# commits itself, so they show as Verified without a key in CI, and they
# are authored by whoever owns the token.
path="repos/$TAP/contents/Formula/ttmux.rb"
old_sha="$(gh api "$path" -q .sha 2>/dev/null || true)"
if [ -n "$old_sha" ] &&
  gh api "$path" -H "Accept: application/vnd.github.raw" | cmp -s - "$work/ttmux.rb"; then
  echo "tap already at $VERSION"
  exit 0
fi
gh api -X PUT "$path" --silent \
  -f message="ttmux $VERSION" \
  -f content="$(base64 < "$work/ttmux.rb" | tr -d '\n')" \
  ${old_sha:+-f sha="$old_sha"}
echo "tap updated to $VERSION"
